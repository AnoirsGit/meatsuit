/**
 * Пауза «подумать» между действиями. Скрипт, который получил страницу и через полсекунды
 * уже нажимает, выдаёт себя ритмом: человек сначала смотрит. Driver перед каждым
 * действием спрашивает здесь, сколько ещё надо подождать с конца прошлого действия,
 * и ждёт только недостающее: если клиент и так думал десять секунд, ждать нечего.
 *
 * Виды пауз (медианы в мс, логнормальный разброс, границы). Числа — стартовые догадки
 * автора по ощущению, не измеренные на людях:
 *   page  страница сменилась с прошлого действия: осмотреться, найти нужное;
 *   act   следующее нажатие на той же странице;
 *   keys  печать или клавиша после клика: рука уже на клавиатуре, план печати сам
 *         добавляет реакцию перед первой буквой (human/keys.js).
 */
const { clamp, lognormal } = require('./random');

const KINDS = {
  page: { median: 1800, sigma: 0.5, lo: 700, hi: 6000 },
  act: { median: 650, sigma: 0.45, lo: 250, hi: 2500 },
  keys: { median: 300, sigma: 0.4, lo: 120, hi: 1200 },
};

/** Сколько человек думает перед действием вида kind, мс (целое). */
function reactionMs(kind, rnd = Math.random) {
  const k = KINDS[kind];
  if (!k) throw new Error(`pace: неизвестный вид паузы «${kind}» (бывают ${Object.keys(KINDS).join(', ')})`);
  return Math.round(clamp(lognormal(rnd, k.median, k.sigma), k.lo, k.hi));
}

/** Сколько ещё ждать: нужная пауза минус уже прошедшее; не меньше нуля. */
const owed = (needMs, elapsedMs) => Math.max(0, Math.round(needMs - Math.max(0, elapsedMs || 0)));

module.exports = { reactionMs, owed, KINDS };
